package com.taskflow.model;

import com.fasterxml.jackson.annotation.JsonIgnore;
import com.framework.extension.user.IUser;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;

import java.util.Collection;
import java.util.List;

/**
 * Usuário da instância TaskFlow (o gestor que faz login e cria projetos).
 * Guardado em memória, como o restante dos dados desta instância. Distinto
 * de Collaborator: AppUser é quem acessa o sistema; Collaborator é quem
 * recebe tarefas delegadas (podendo ou não ter uma conta).
 */
public class AppUser implements UserDetails, IUser {

    private Long id;
    private String name;
    private String email;

    @JsonIgnore
    private String password;

    public AppUser() {
    }

    public AppUser(Long id, String name, String email, String password) {
        this.id = id;
        this.name = name;
        this.email = email;
        this.password = password;
    }

    @Override
    public Long getId() {
        return id;
    }

    @Override
    public String getName() {
        return name;
    }

    @Override
    public String getEmail() {
        return email;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public void setName(String name) {
        this.name = name;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public void setPassword(String password) {
        this.password = password;
    }

    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        return List.of();
    }

    @Override
    public String getPassword() {
        return this.password;
    }

    @Override
    public String getUsername() {
        return this.email;
    }

    @Override
    public boolean isAccountNonExpired() {
        return true;
    }

    @Override
    public boolean isAccountNonLocked() {
        return true;
    }

    @Override
    public boolean isCredentialsNonExpired() {
        return true;
    }

    @Override
    public boolean isEnabled() {
        return true;
    }
}
